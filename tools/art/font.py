def glyph(font, ch):
    rows = font.get(ch.upper(), font[' ']).split('|')
    return np.array([[c == '#' for c in r] for r in rows])


def render(text, font=BIG):
    cols = []
    for i, ch in enumerate(text):
        g = glyph(font, ch)
        cols.append(g)
        if i < len(text) - 1:
            cols.append(np.zeros((g.shape[0], 1), bool))
    return np.hstack(cols)


def draw(canvas, x, y, text, color, font=BIG, shadow=None):
    bm = render(text, font)
    if shadow:
        for j, i in zip(*np.where(bm)):
            canvas.set(x + i + 1, y + j + 1, shadow)
    for j, i in zip(*np.where(bm)):
        canvas.set(x + i, y + j, color)
    return bm.shape[1]


def width(text, font=BIG):
    return render(text, font).shape[1]
